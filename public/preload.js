const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  selectFiles: () => ipcRenderer.invoke('dialog:openFiles'),
  selectSubtitles: () => ipcRenderer.invoke('dialog:openSubtitles'),
  getSubtitleMetadata: (...args) => ipcRenderer.invoke('file:getSubtitleMetadata', ...args),
  getFileMetadata: (...args) => ipcRenderer.invoke('file:getMetadata', ...args),
  writeMetadata: (...args) => ipcRenderer.invoke('file:writeMetadata', ...args),
  batchWriteMetadata: (...args) => ipcRenderer.invoke('file:batchWriteMetadata', ...args),
  searchTMDB: (...args) => ipcRenderer.invoke('tmdb:search', ...args),
  getSeriesDetails: (...args) => ipcRenderer.invoke('tmdb:getSeriesDetails', ...args),
  getSeasonDetails: (...args) => ipcRenderer.invoke('tmdb:getSeasonDetails', ...args),
  getImages: (...args) => ipcRenderer.invoke('tmdb:getImages', ...args),
  getSetting: (...args) => ipcRenderer.invoke('store:get', ...args),
  setSetting: (...args) => ipcRenderer.invoke('store:set', ...args),
  selectOutputFolder: () => ipcRenderer.invoke('dialog:selectFolder'),
  processFiles: (...args) => ipcRenderer.invoke('file:processFiles', ...args),
  onProgress: (callback) => ipcRenderer.on('progress', (event, data) => callback(data)),
  removeProgressListener: () => ipcRenderer.removeAllListeners('progress'),
  getMovieDetails: (...args) => ipcRenderer.invoke('tmdb:getMovieDetails', ...args),
  copyFileToTemp: (...args) => ipcRenderer.invoke('file:copyToTemp', ...args),
  downloadImage: (...args) => ipcRenderer.invoke('file:downloadImage', ...args),
  getCredits: (...args) => ipcRenderer.invoke('tmdb:getCredits', ...args),
  getImageDataUrl: (...args) => ipcRenderer.invoke('file:getImageDataUrl', ...args),
  extractCover: (...args) => ipcRenderer.invoke('file:extractCover', ...args),
  onFilesDropped: (callback) => ipcRenderer.on('dropped-files', (event, paths) => callback(paths)),
  makeOffline: (type, id) => ipcRenderer.invoke('tmdb:makeOffline', type, id),
  getOfflineList: () => ipcRenderer.invoke('tmdb:getOfflineList'),
  deleteOfflineItem: (type, id) => ipcRenderer.invoke('tmdb:deleteOfflineItem', type, id),
  deleteAllOffline: () => ipcRenderer.invoke('tmdb:deleteAllOffline'),
});